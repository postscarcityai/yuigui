// yuicss build: tokens.json in, one stylesheet out.
//
//   node site/lib/yuicss/build.mjs           write tokens.mjs, classes.json and public/yuicss/yuicss.css
//   node site/lib/yuicss/build.mjs --check   exit 1 when any of them is stale (CI, the site build)
//
// Layers, in order: the variables for Yui's own look (light and dark) and the
// static scales from tokens.json; base.css (classless defaults); the utilities
// generated from the scales plus utilities.css; components.css. Every rule is
// scoped under .yuicss, which the test checks.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(here, "..", "..");
const check = process.argv.includes("--check");

const tokens = JSON.parse(readFileSync(path.join(here, "tokens.json"), "utf8"));
const tokensMjs = `// Generated from tokens.json by build.mjs. Do not edit; edit tokens.json and run \`node site/lib/yuicss/build.mjs\`.\nexport default ${JSON.stringify(tokens, null, 2)};\n`;

const out = {};
out["lib/yuicss/tokens.mjs"] = tokensMjs;
// theme.mjs imports tokens.mjs, so it is written (or compared) first.
if (!check) writeFileSync(path.join(here, "tokens.mjs"), tokensMjs);
const { css: lookCss } = await import("./theme.mjs");
const { YUI } = await import("../yl/look.mjs");

const px = (n) => (n === 0 ? "0" : `${n}px`);
const P = ".yuicss ";
const rule = (sel, body) => `${P}${sel} { ${body} }`;
const esc = (k) => String(k).replace(/\//g, "\\/").replace(/\./g, "\\.");

// ---------- the variables ----------
const T = tokens.type, S = tokens.space, SH = tokens.shape;
const statics = [];
for (const [k, v] of Object.entries(T.scale)) statics.push(`--text-${k}: ${px(v)}`);
for (const [k, v] of Object.entries(T.leading)) statics.push(`--leading-${k}: ${v}`);
for (const [k, v] of Object.entries(T.weight)) statics.push(`--weight-${k}: ${v}`);
statics.push(`--weight-body: ${T.body}`);
for (const [k, v] of Object.entries(T.fonts)) statics.push(`--font-${k}: ${v}`);
for (const [k, v] of Object.entries(S.scale)) statics.push(`--space-${k}: ${px(v)}`);
statics.push(`--gap: ${px(S.gap)}`, `--pad: ${px(S.pad)}`, `--control: ${px(S.control)}`, `--tap: ${px(S.tap)}`, `--line-w: ${SH.line}px`);
for (const [k, v] of Object.entries(SH.fixed)) statics.push(`--radius-${k}: ${px(v)}`);

const header = `/* yuicss v${tokens.version}: how Yui looks, as one stylesheet. Generated by site/lib/yuicss/build.mjs from tokens.json,
   base.css, utilities.css and components.css. Gallery and contract: https://www.yuigui.com/yuicss
   Scope everything under .yuicss (the body in the app, a frame on a page). Add .dark for the dark palette. */`;
const varsBlock = [
  // A clean slate: on a page with other CSS (the site), every element under .yuicss goes back to the
  // browser's own styles first, so a page's .card or .toggle never leaks into a screen. In the app's web
  // view there is nothing to revert. Custom properties are not part of `all`, so the tokens stay.
  // SVG is left alone: its presentation attributes (d, cx, r) live in the author origin and would go too.
  `.yuicss, .yuicss :not(svg, svg *), .yuicss :not(svg, svg *)::before, .yuicss :not(svg, svg *)::after { all: revert; }`,
  `.yuicss {\n${statics.map((s) => `  ${s};`).join("\n")}\n}`,
  lookCss(YUI, "light", ".yuicss, .yuicss.light").replace("{", "{\n  color-scheme: light;"),
  lookCss(YUI, "dark", '.yuicss.dark, [data-theme="dark"] .yuicss:not(.light)').replace("{", "{\n  color-scheme: dark;"),
].join("\n");

// ---------- generated utilities ----------
const u = [];
const sizes = { ...S.scale, ...S.sizes };
const sides = { "": ["{p}"], x: ["{p}-left", "{p}-right"], y: ["{p}-top", "{p}-bottom"], t: ["{p}-top"], r: ["{p}-right"], b: ["{p}-bottom"], l: ["{p}-left"] };
for (const [short, prop] of [["p", "padding"], ["m", "margin"]]) {
  for (const [k, v] of Object.entries(S.scale)) {
    for (const [side, props] of Object.entries(sides)) {
      u.push(rule(`.${short}${side}-${k}`, props.map((p) => `${p.replace("{p}", prop)}: ${px(v)};`).join(" ")));
      if (short === "m" && v > 0) u.push(rule(`.-${short}${side}-${k}`, props.map((p) => `${p.replace("{p}", prop)}: -${px(v)};`).join(" ")));
    }
  }
  if (short === "m") for (const [side, props] of Object.entries(sides)) u.push(rule(`.m${side}-auto`, props.map((p) => `${p.replace("{p}", prop)}: auto;`).join(" ")));
}
for (const [k, v] of Object.entries(S.scale)) {
  u.push(rule(`.gap-${k}`, `gap: ${px(v)};`), rule(`.gap-x-${k}`, `column-gap: ${px(v)};`), rule(`.gap-y-${k}`, `row-gap: ${px(v)};`));
  u.push(rule(`.space-y-${k} > * + *`, `margin-top: ${px(v)};`), rule(`.space-x-${k} > * + *`, `margin-left: ${px(v)};`));
}
for (const [k, v] of Object.entries(sizes)) {
  u.push(rule(`.w-${k}`, `width: ${px(v)};`), rule(`.h-${k}`, `height: ${px(v)};`), rule(`.size-${k}`, `width: ${px(v)}; height: ${px(v)};`));
  u.push(rule(`.min-w-${k}`, `min-width: ${px(v)};`), rule(`.min-h-${k}`, `min-height: ${px(v)};`), rule(`.max-w-${k}`, `max-width: ${px(v)};`), rule(`.max-h-${k}`, `max-height: ${px(v)};`));
}
for (const [k, v] of Object.entries({ "1/2": "50%", "1/3": "33.333%", "2/3": "66.667%", "1/4": "25%", "3/4": "75%", "1/5": "20%", "2/5": "40%", "3/5": "60%", "4/5": "80%", full: "100%", auto: "auto" })) {
  u.push(rule(`.w-${esc(k)}`, `width: ${v};`), rule(`.h-${esc(k)}`, `height: ${v};`));
}
u.push(rule(".w-screen", "width: 100vw;"), rule(".h-screen", "height: 100dvh;"), rule(".min-h-screen", "min-height: 100dvh;"), rule(".min-h-full", "min-height: 100%;"), rule(".max-w-full", "max-width: 100%;"), rule(".max-w-xs", "max-width: 320px;"), rule(".max-w-sm", "max-width: 384px;"), rule(".max-w-md", "max-width: 448px;"), rule(".max-w-prose", "max-width: 60ch;"), rule(".w-fit", "width: fit-content;"), rule(".h-fit", "height: fit-content;"), rule(".size-full", "width: 100%; height: 100%;"));
const leadingFor = { xs: "leading-normal", sm: "leading-normal", base: "leading-normal", lg: "leading-snug", xl: "leading-snug", "2xl": "leading-tight", "3xl": "leading-tight", "4xl": "leading-tight" };
for (const k of Object.keys(T.scale)) u.push(rule(`.text-${k}`, `font-size: var(--text-${k}); line-height: var(--${leadingFor[k] || "leading-normal"});`));
for (const [k, v] of Object.entries(T.leading)) u.push(rule(`.leading-${k}`, `line-height: ${v};`));
u.push(rule(".leading-none", "line-height: 1;"));
for (const [names, w] of [[["font-normal", "regular"], T.body], [["medium", "font-medium"], T.weight.regular], [["semibold", "font-semibold"], T.weight.semibold], [["bold", "font-bold"], T.weight.bold], [["heavy", "font-heavy", "font-extrabold", "font-black"], T.weight.heavy]]) {
  u.push(`${names.map((n) => `${P}.${n}`).join(", ")} { font-weight: ${w}; }`);
}
u.push(rule(".font-heading", "font-weight: var(--weight-heading);"));
// colors: text-*, bg-*, border-*, fill-*, stroke-*
const colors = ["paper", "surface", "ink", "muted", "line", "accent", "accent-ink", "accent-text", "good", "warn", "bad", "good-ink", "warn-ink", "bad-ink", "good-text", "warn-text", "bad-text", "good-soft", "warn-soft", "bad-soft", ...Object.keys(tokens.color.ramp.light).concat("500").sort((a, b) => a - b).map((k) => `accent-${k}`)];
for (const c of colors) {
  const v = `var(--${c})`;
  // text-good reads as text: the text shade, not the fill.
  const textV = ["good", "warn", "bad"].includes(c) ? `var(--${c}-text)` : v;
  u.push(rule(`.text-${c}`, `color: ${textV};`), rule(`.bg-${c}`, `background-color: ${v};`), rule(`.border-${c}`, `border-color: ${v};`), rule(`.fill-${c}`, `fill: ${v};`), rule(`.stroke-${c}`, `stroke: ${v};`));
}
u.push(rule(".text-white", "color: #fff;"), rule(".bg-white", "background-color: #fff;"), rule(".text-black", "color: #000;"), rule(".bg-black", "background-color: #000;"), rule(".bg-transparent", "background-color: transparent;"), rule(".border-transparent", "border-color: transparent;"), rule(".text-current", "color: currentColor;"), rule(".fill-current", "fill: currentColor;"), rule(".stroke-current", "stroke: currentColor;"));
u.push(rule(".bg-accent-soft", "background-color: var(--accent-100);"), rule(".bg-gradient", "background-image: linear-gradient(160deg, var(--accent-300), var(--accent) 60%, var(--accent-600));"), rule(".bg-gradient-soft", "background-image: linear-gradient(160deg, var(--accent-50), var(--accent-200));"));
// radius
u.push(rule(".rounded", "border-radius: var(--radius);"), rule(".rounded-control", "border-radius: var(--radius-control);"));
for (const k of Object.keys(SH.fixed)) u.push(rule(`.rounded-${k}`, `border-radius: var(--radius-${k});`));
for (const [side, props] of [["t", ["top-left", "top-right"]], ["b", ["bottom-left", "bottom-right"]], ["l", ["top-left", "bottom-left"]], ["r", ["top-right", "bottom-right"]]]) {
  u.push(rule(`.rounded-${side}`, props.map((p) => `border-${p}-radius: var(--radius);`).join(" ")));
  u.push(rule(`.rounded-${side}-none`, props.map((p) => `border-${p}-radius: 0;`).join(" ")));
  u.push(rule(`.rounded-${side}-full`, props.map((p) => `border-${p}-radius: 999px;`).join(" ")));
}
for (const v of [0, 10, 25, 50, 75, 90, 100]) u.push(rule(`.opacity-${v}`, `opacity: ${v / 100};`));
for (const v of [0, 10, 20, 30, 40, 50]) u.push(rule(`.z-${v}`, `z-index: ${v};`));
for (let i = 1; i <= 12; i++) u.push(rule(`.delay-${i}`, `animation-delay: calc(var(--mo-stagger) * ${i});`));
u.push(rule(".duration-fast", "animation-duration: calc(var(--mo-enter) * .6); transition-duration: calc(var(--mo-handoff) * .6);"), rule(".duration-slow", "animation-duration: calc(var(--mo-enter) * 1.8); transition-duration: calc(var(--mo-handoff) * 1.8);"));
for (const [k, v] of Object.entries({ 0: "0", 1: "1px", 2: "2px", 4: "4px" })) u.push(rule(`.border-${k}`, `border-width: ${v}; border-style: solid; border-color: var(--line);`));

const read = (f) => readFileSync(path.join(here, f), "utf8").trim();
const sheet = [header, varsBlock, read("base.css"), `/* yuicss layer 3: utilities generated from tokens.json */\n${u.join("\n")}`, read("utilities.css"), read("components.css")].join("\n\n") + "\n";
out["public/yuicss/yuicss.css"] = sheet;

// The contract: every class name the sheet styles, for the gallery and the renderer.
const classes = [...new Set([...sheet.matchAll(/\.yuicss(?:\.(?:dark|light|still))?\s+[^{]*?(?=\{)/g)].flatMap((m) => [...m[0].matchAll(/\.(-?[a-zA-Z][\w-]*(?:\\\/[\w-]+)?)/g)].map((c) => c[1].replace(/\\\//g, "/"))).filter((c) => c !== "yuicss"))].sort();
const elements = [...new Set([...read("base.css").matchAll(/\.yuicss\s+([a-z][a-z0-9]*)\b(?![-\w])/g)].map((m) => m[1]))].sort();
out["lib/yuicss/classes.json"] = JSON.stringify({ version: tokens.version, bytes: Buffer.byteLength(sheet), classes, elements }, null, 2) + "\n";

let stale = [];
for (const [rel, text] of Object.entries(out)) {
  const file = path.join(site, rel);
  const same = existsSync(file) && readFileSync(file, "utf8") === text;
  if (check) { if (!same) stale.push(rel); continue; }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log(`${same ? "same " : "wrote"} ${rel} (${Buffer.byteLength(text)} bytes)`);
}
if (check) {
  if (stale.length) { console.error(`yuicss is stale: ${stale.join(", ")}. Run node site/lib/yuicss/build.mjs and commit.`); process.exit(1); }
  console.log(`yuicss fresh: ${classes.length} classes, ${elements.length} elements, ${Buffer.byteLength(sheet)} bytes`);
}
